# 重复键自检：Python 字面量里**后写的键会静默覆盖先写的**。
# 表面上改了一条候选，实际生效的却是下面那条——本项目已踩到：
# 文王 / 武王 / 景帝 各写过两份（2026-09-26 AI 判定落地时发现「武王」加了曹操
# 却不生效，因为生效的是下方另一份）。查重只能靠 AST，且必须写在词典旁边。
def _assert_no_dup_dict_keys(var_name):
    import ast as _ast
    tree = _ast.parse(open(__file__, encoding="utf-8").read())
    for node in _ast.walk(tree):
        if isinstance(node, _ast.Assign) and len(node.targets) == 1 \
                and getattr(node.targets[0], "id", None) == var_name \
                and isinstance(node.value, _ast.Dict):
            keys = [k.value for k in node.value.keys]
            dup = sorted({k for k in keys if keys.count(k) > 1})
            if dup:
                raise SystemExit(
                    "{} 有重复键，后写者会静默覆盖先写者：{}".format(
                        var_name, "、".join(map(str, dup))))


