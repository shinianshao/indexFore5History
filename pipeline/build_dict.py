# ===== 《三国志》篇目主人公 结束 =====

def main():
    from opencc import OpenCC

    t2s = OpenCC("t2s")
    os.makedirs(DICT, exist_ok=True)

    persons = []
    seen_ids = set()
    alias_owner = {}          # 别名 -> 归属人数，用于发现冲突
    declared_owner = {}       # 繁体别名 -> [声明它的人物 id]，按声明顺序
    total_aliases = 0

    for pid, name, trad, dynasty, title, summary, aliases_trad in PERSONS:
        if pid in seen_ids:
            raise SystemExit("重复 person id: {}".format(pid))
        seen_ids.add(pid)

        variants = []
        for item in [trad] + list(aliases_trad):
            declared_owner.setdefault(item, []).append(pid)
            for form in (item, t2s.convert(item)):
                if form and form not in variants:
                    variants.append(form)
        if name not in variants:
            variants.append(name)

        for form in variants:
            alias_owner.setdefault(form, set()).add(pid)
        total_aliases += len(variants)

        persons.append({
            "id": pid,
            "name": name,
            "tradName": trad,
            "dynasty": dynasty,
            "title": title,
            "summary": summary,
            "aliases": variants,
        })
        # 书作用域：多表 **并集** 合并（跨书同人只扩 books，不建新 pid）。
        # 旧「后表覆盖」会把 ["hhs","sgz"] 冲成 ["js"]，导致前书漏召。
        # 不加闸则新书人物会撞旧书同名异人（王成/刘志前科）。
        _books = []
        for _tbl in (PERSON_BOOKS_LIUZE, PERSON_BOOKS_SJ, PERSON_BOOKS_HS,
                     PERSON_BOOKS_HHS, PERSON_BOOKS_SGZ, PERSON_BOOKS_JS,
                     PERSON_BOOKS_TIER3, PERSON_BOOKS_ACCURACY_FIX):
            if pid in _tbl:
                for _b in _tbl[pid]:
                    if _b not in _books:
                        _books.append(_b)
        if _books:
            persons[-1]["books"] = list(_books)

    # --- 泛称识别与候选推导 ------------------------------------------------
    # 每个人物的兼容性词表（简体），用于判断「谁可能持有某称号」
    tokens = {}
    for person in persons:
        acc = set()
        for item in [person["name"], t2s.convert(person["tradName"]),
                     person["title"]] + list(person["aliases"]):
            if not item:
                continue
            simp = t2s.convert(item)
            if any(word in simp for word in OFFICE_WORDS):
                continue
            acc.add(simp)
        tokens[person["id"]] = acc

    generic_surfaces = {}     # 繁体别名 -> 核心词（None 表示手工声明）
    for item in declared_owner:
        simp = t2s.convert(item)
        for suf in sorted(GENERIC_CORE_SUFFIXES, key=len, reverse=True):
            if simp.endswith(suf) and len(simp) > len(suf):
                core = simp[:-len(suf)]
                if core in GENERIC_CORES:
                    generic_surfaces[item] = core
                break
    for item in GENERIC_MANUAL:
        if item not in declared_owner:
            raise SystemExit("手工泛称 {} 未登记在任何人物别名里".format(item))
        generic_surfaces[item] = None

    generic_entries = []
    for item, core in generic_surfaces.items():
        if core is None:
            candidates = list(GENERIC_MANUAL[item])
        else:
            candidates = list(dict.fromkeys(declared_owner[item]))
            own_simp = t2s.convert(item)
            for person in persons:
                pid = person["id"]
                if pid in candidates:
                    continue
                if any(t != own_simp and title_like(t, core)
                       for t in tokens[pid]):
                    candidates.append(pid)
        # 称号对应不到 2 人时通常按普通别名处理，但「莊王/景公/隱公/孝公/文侯」虽库中仅一人，
        # 却必须走泛称以通过 GENERIC_CONTEXT_RULES 硬排除其他诸侯或同号伪切。
        if len(candidates) < 2 and item not in ("莊王", "庄王", "景公", "隱公", "隐公", "孝公", "文侯"):
            continue
        for pid in candidates:
            if pid not in seen_ids:
                raise SystemExit("泛称 {} 引用了不存在的人物 {}".format(item, pid))
        default = GENERIC_DEFAULT.get(item, candidates[0])
        if default not in candidates:
            raise SystemExit("泛称 {} 的默认归属 {} 不在候选内".format(item, default))
        forms = []
        for form in (item, t2s.convert(item)):
            if form not in forms:
                forms.append(form)
        entry_out = {
            "alias": item,
            "forms": forms,
            "core": core,
            "candidates": candidates,
            "default": default,
        }
        bc = (GENERIC_BOOK_CANDIDATES.get(item) or {})
        if bc:
            entry_out["bookCandidates"] = bc
        cr = GENERIC_CONTEXT_RULES.get(item) or []
        # 目标必须是本泛称的候选，写错了直接报错——避免规则悄悄失效
        for _scope, _key, _target in cr:
            if _target is not None and _target not in candidates:
                raise SystemExit(
                    "泛称 {} 的上下文规则目标 {} 不在候选内".format(item, _target))
        if cr:
            entry_out["ctxRules"] = cr
        generic_entries.append(entry_out)
    generic_forms = set()
    for entry in generic_entries:
        generic_forms.update(entry["forms"])


    # 校验篇目主人公引用
    missing = []
    chapter_owners = {}
    for volume, pids in sorted(CHAPTER_OWNERS.items()):
        for pid in pids:
            if pid not in seen_ids:
                missing.append({"volume": volume, "pid": pid})
        chapter_owners["sj-{:03d}".format(volume)] = list(pids)

    if len(CHAPTER_OWNERS) != 130:
        raise SystemExit("篇目数应为 130，实际 {}".format(len(CHAPTER_OWNERS)))

    # 《汉书》篇主表：键是卷 slug（"015b"/"027下之上"），产出时加 hs- 前缀。
    # 与史记共用 chapterOwners 一张表——键是 chapterId，本来就是跨书唯一的。
    hs_volumes = common.load_json(os.path.join(DICT, "volumes", "hs.json")) or {}
    for slug, pids in sorted(CHAPTER_OWNERS_HS.items(),
                             key=lambda kv: volume_sort_key(kv[0])):
        for pid in pids:
            if pid not in seen_ids:
                missing.append({"volume": "hs-" + slug, "pid": pid})
        chapter_owners["hs-{}".format(slug)] = list(pids)
    if missing:
        raise SystemExit("篇目主人公引用了不存在的人物: {}".format(missing))
    if hs_volumes and len(CHAPTER_OWNERS_HS) != len(hs_volumes):
        raise SystemExit("汉书篇目数应为 {}，实际 {}".format(
            len(hs_volumes), len(CHAPTER_OWNERS_HS)))

    # 《后汉书》篇主表：键是卷 slug（"1上"/"28下"/"109"），产出时加 hhs- 前缀。
    hhs_volumes = common.load_json(os.path.join(DICT, "volumes", "hhs.json")) or {}
    for slug, pids in sorted(CHAPTER_OWNERS_HHS.items(),
                             key=lambda kv: volume_sort_key(kv[0])):
        for pid in pids:
            if pid not in seen_ids:
                missing.append({"volume": "hhs-" + slug, "pid": pid})
        chapter_owners["hhs-{}".format(slug)] = list(pids)
    if missing:
        raise SystemExit("篇目主人公引用了不存在的人物: {}".format(missing))
    if hhs_volumes and len(CHAPTER_OWNERS_HHS) != len(hhs_volumes):
        raise SystemExit("后汉书篇目数应为 {}，实际 {}".format(
            len(hhs_volumes), len(CHAPTER_OWNERS_HHS)))

    # 《三国志》篇目主人公：键是卷 slug（"01"–"65"），产出时加 sgz- 前缀。
    sgz_volumes = common.load_json(os.path.join(DICT, "volumes", "sgz.json")) or {}
    for slug, pids in sorted(CHAPTER_OWNERS_SGZ.items(),
                             key=lambda kv: volume_sort_key(kv[0])):
        for pid in pids:
            if pid not in seen_ids:
                missing.append({"volume": "sgz-" + slug, "pid": pid})
        chapter_owners["sgz-{}".format(slug)] = list(pids)
    if missing:
        raise SystemExit("篇目主人公引用了不存在的人物: {}".format(missing))
    if sgz_volumes and len(CHAPTER_OWNERS_SGZ) != len(sgz_volumes):
        raise SystemExit("三国志篇目数应为 {}，实际 {}".format(
            len(sgz_volumes), len(CHAPTER_OWNERS_SGZ)))

    # 《晋书》篇目主人公：键是卷 slug（"001"–"130"），产出时加 js- 前缀。
    # 帝纪有主；志/载记 R2 先空（载记 30 卷篇主归 R3 君主，与 hhs 民族传同策略）。
    js_volumes = common.load_json(os.path.join(DICT, "volumes", "js.json")) or {}
    for slug, pids in sorted(CHAPTER_OWNERS_JS.items(),
                             key=lambda kv: volume_sort_key(kv[0])):
        for pid in pids:
            if pid not in seen_ids:
                missing.append({"volume": "js-" + slug, "pid": pid})
        chapter_owners["js-{}".format(slug)] = list(pids)
    if missing:
        raise SystemExit("篇目主人公引用了不存在的人物: {}".format(missing))
    if js_volumes and len(CHAPTER_OWNERS_JS) != len(js_volumes):
        raise SystemExit("晋书篇目数应为 {}，实际 {}".format(
            len(js_volumes), len(CHAPTER_OWNERS_JS)))

    # 篇内相关人物：同样校验存在性，且不允许与主人公重复
    chapter_related = {}
    for volume, pids in sorted(CHAPTER_RELATED.items()):
        if volume not in CHAPTER_OWNERS:
            raise SystemExit("篇内相关人物引用了不存在的卷号 {}".format(volume))
        bad = [p for p in pids if p not in seen_ids]
        if bad:
            raise SystemExit("篇内相关人物引用了不存在的人物: {}".format(bad))
        dup = [p for p in pids if p in CHAPTER_OWNERS[volume]]
        if dup:
            raise SystemExit("卷 {} 的相关人物与主人公重复: {}".format(volume, dup))
        chapter_related["sj-{:03d}".format(volume)] = list(pids)

    # 单字指代：校验人物存在，并把「卷号」解析成 chapterId
    scoped = []
    for pid, ch, vols in SCOPED_ALIASES:
        if pid not in seen_ids:
            raise SystemExit("单字指代引用了不存在的人物: {}".format(pid))
        if vols is None:
            chapters = [k for k, v in chapter_owners.items() if pid in v]
            if not chapters:
                raise SystemExit("{} 无主人公篇目，单字指代需显式指定篇目".format(pid))
        else:
            chapters = ["sj-{:03d}".format(v) for v in vols]
        scoped.append({"pid": pid, "char": ch, "chapters": chapters})

    data = {
        "_comment": "由 pipeline/build_dict.py 生成，请勿直接编辑；改词典请改 build_dict.py。"
                    "aliases 含繁简两套：繁体用于匹配维基文库正文，简体用于接受用户查询。"
                    "genericAliases 是泛称（称号类）别名，由 annotate.py 按篇目上下文判定归属，"
                    "不参与全局匹配——详见该文件 resolve_generic()。",
        "persons": persons,
        "chapterOwners": chapter_owners,
        "chapterRelated": chapter_related,
        "scopedAliases": scoped,
        "genericAliases": generic_entries,
    }
    with open(os.path.join(DICT, "people.json"), "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)

    # 冲突别名：同一别名归属多个人物，匹配时会被长者优先占据，需人工留意。
    # 泛称不列入——它们本来就要多人共享，由 runtime 消歧处理。
    conflicts = sorted(
        ({"alias": a, "owners": sorted(v), "count": len(v)}
         for a, v in alias_owner.items() if len(v) > 1 and a not in generic_forms),
        key=lambda x: (-x["count"], x["alias"]),
    )

    name_of = {p["id"]: p["name"] for p in persons}

    report = {
        "personCount": len(persons),
        "aliasTotal": total_aliases,
        "avgAliases": round(total_aliases / max(len(persons), 1), 1),
        "chaptersWithOwner": sum(1 for v in CHAPTER_OWNERS.values() if v),
        "chaptersWithoutOwner": [v for v in sorted(CHAPTER_OWNERS) if not CHAPTER_OWNERS[v]],
        "scopedAliases": scoped,
        "genericAliasCount": len(generic_entries),
        "genericAliases": [
            {"alias": e["alias"], "core": e["core"],
             "candidates": [name_of[c] for c in e["candidates"]],
             "default": name_of[e["default"]]}
            for e in generic_entries
        ],
        "chapterRelatedCount": sum(len(v) for v in chapter_related.values()),
        "conflictCount": len(conflicts),
        "conflicts": conflicts[:40],
        "singleCharAliases": sorted(a for a in alias_owner if len(a) == 1),
    }
    with open(os.path.join(ROOT, "pipeline", "_dict_report.json"), "w", encoding="utf-8") as fh:
        json.dump(report, fh, ensure_ascii=False, indent=2)

    # 同步编译地名词典（workbook/places.xlsx → places.json）
    # 使 build_dict.py 真正实现「讀 workbook/*.xlsx → people.json / places.json」
    try:
        import build_places
        build_places.main()
    except Exception as e:
        print("⚠ 自动生成 places.json 失败：{}".format(e))
        raise


if __name__ == "__main__":
    main()

