# 下面是权威源_loader：表格优先，种子数据兜底。见函数内说明。
def _load_persons():                       # noqa: E302
    """PERSONS 的权威源：**优先读 workbook/persons.xlsx**（人写的表格），
    表格不存在时回退 persons_data.py（拆分时留下的种子数据）。

    这一行是 docs/21 P0 的收口：Excel 由「视图」升级为「权威源」。

    ⚠️ 三条铁律：
      1. **只读**。pipeline 任何地方都不许回写 xlsx——否则重建会冲掉你的审定。
      2. **只认数据列**。pinyin / in_<书> / 命中数 是给你排序筛选的辅助列，
         这里一律忽略，改了不影响产出。
      3. **空行与 status≠active 的行跳过**，所以「删条目」只需把状态改成 dead，
         不必物理删行（保留痕迹，方便改回来）。

    xlsx 列序见 build_workbook.py 的 sheet_persons()。
    返回元组格式：(id, 简体名, 繁体名, 朝代, 头衔, 简介, [别名...])
    """
    # 注意：本文件的 ROOT 是字符串（不是 Path），别顺手写 ROOT / "..."
    xlsx = os.path.join(ROOT, "workbook", "persons.xlsx")
    if not os.path.exists(xlsx):
        # 回退要**喊出来**：静默回退会让「我明明改了表格怎么没生效」变成最难查的 bug
        print("⚠ 未找到 {}，本次回退 persons_data.py 种子数据。".format(xlsx))
        print("  若你已编辑过表格，检查一下文件是不是被移动或改名了。")
        from persons_data import PERSONS as _seed
        return _seed
    try:
        from openpyxl import load_workbook
    except ImportError:                                # pragma: no cover
        from persons_data import PERSONS as _seed
        return _seed

    wb = load_workbook(xlsx, read_only=True)
    try:
        ws = wb["人物"]
        out = []
        for row in ws.iter_rows(min_row=2, values_only=True):
            pid = (row[0] or "").strip()
            trad = (row[1] or "").strip()
            if not pid or not trad:
                continue                               # 空行或半填行
            status = (row[7] or "active").strip()
            if status and status != "active":
                continue                               # dead / 弃用
            aliases = [x.strip() for x in str(row[6] or "").split("|") if x.strip()]
            out.append((pid, (row[2] or "").strip(), trad,
                        (row[3] or "").strip(), (row[4] or "").strip(),
                        (row[5] or "").strip(), aliases))
        if not out:
            raise ValueError("persons.xlsx 没读到任何有效行，回退种子数据")
        return out
    finally:
        wb.close()


