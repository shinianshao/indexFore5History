# 名字的 3 字前缀也可能是阻断串（鄭安**平**、夏徵**舒**），匹配时按 2~4 字逐个试。
# 注意：起首字若已被 BARE_OFF 全局禁用（如「紀」），本表再多写也是死规则，
# 故 main() 会拒绝这类条目——「紀成」「紀通」就是这么剔除的。


def main():
    from opencc import OpenCC

    t2s = OpenCC("t2s")
    os.makedirs(DICT, exist_ok=True)

    places = []
    seen = set()
    total_aliases = 0

    for row in list(PLACES) + list(PLACES_DL) + list(PLACES_JS):
        pid, name, trad = row[0], row[1], row[2]
        kind, era, summary = row[3], row[4], row[5]
        extra = list(row[6]) if len(row) > 6 else []
        if pid in seen:
            raise SystemExit("重复 place id: {}".format(pid))
        seen.add(pid)

        variants = []
        for item in [trad] + extra + list(EXTRA_ALIASES.get(pid, [])):
            for form in (item, t2s.convert(item)):
                if form and form not in variants:
                    variants.append(form)
        if name not in variants:
            variants.append(name)

        total_aliases += len(variants)
        row_out = {
            "id": pid,
            "name": name,
            "tradName": trad,
            "kind": kind,
            "era": era,
            "summary": summary,
            "aliases": variants,
            "isChar": len(trad) == 1,
            "bare": not (len(trad) == 1 and trad in BARE_OFF),
        }
        # 书作用域：带 books 的地名只在指定书内匹配。
        # 《地理志》郡县一律限「hs」——这批县名若全局生效，
        # 《史记》里的同名用法会被整批拉进来，史記侧必然回归。
        if pid in PLACE_BOOKS_DL:
            row_out["books"] = list(PLACE_BOOKS_DL[pid])
        places.append(row_out)

    # 名字唯一性：同一个地名字串挂到两个地点上，匹配时只能取其一，
    # 必然有一半数据静默丢失（「河东」既建过郡条目又建过地域条目就踩过）。
    # 这种情况要么合并、要么走「同称异地」显式登记，不允许撞车。
    name_owner = {}
    for p in places:
        for form in p["aliases"]:
            prev = name_owner.get(form)
            if prev and prev != p["id"]:
                raise SystemExit(
                    "地名字串 {!r} 同时挂在 {} 与 {} 上，请合并或显式登记同称异地"
                    .format(form, prev, p["id"]))
            name_owner[form] = p["id"]

    # 守卫表校验：aft/bfr 里的字不该是地名自身用字
    # 守卫表的键必须是**某个地名的某种写法**（含别名——「荊」是「楚」的别称，
    # 不是楚的繁体名）。对不上就说明守卫白写了，直接报错。
    guards = {}
    all_forms = set()
    for p in places:
        all_forms.update(p["aliases"])
    for ch, spec in CHAR_GUARDS.items():
        ch = ch.rstrip("_")
        if ch not in all_forms:
            raise SystemExit("守卫表 {!r} 不是任何地名的写法".format(ch))
        guards[ch] = {
            "aft": "".join(dict.fromkeys(spec.get("aft", ""))),
            "bfr": "".join(dict.fromkeys(spec.get("bfr", ""))),
        }

    # 人名阻断表校验。四道，缺一道这张表就会悄悄失效或误伤：
    #   起首字不是单字地名 → 这条规则永远不会命中（死规则，白写）
    #   起首字已被 BARE_OFF 禁用 → 同上，永远不会命中
    #   整串正好是某个地名写法 → 会把真实地名整片挡掉（误伤）
    #   长度不在 2~4      → 匹配时按 2~4 字试，超出的永远匹配不上
    char_forms = set()
    for p in places:
        if p["isChar"]:
            char_forms.update(p["aliases"])
    for w in NAME_BLOCK:
        if not (2 <= len(w) <= 4):
            raise SystemExit("人名阻断串 {!r} 长度不在 2~4".format(w))
        if w[0] not in char_forms:
            raise SystemExit("人名阻断串 {!r} 的起首字不是单字地名".format(w))
        if w[0] in BARE_OFF:
            raise SystemExit(
                "人名阻断串 {!r} 的起首字已被 BARE_OFF 全局禁用，是死规则".format(w))
        if w in all_forms:
            raise SystemExit("人名阻断串 {!r} 同时是地名写法，会误伤地名".format(w))

    data = {
        "_comment": "由 pipeline/build_places.py 生成，请勿直接编辑。"
                    "places[].aliases 含繁简两套：繁体用于匹配维基文库正文，"
                    "简体用于接受用户查询。isChar 表示单字地名，"
                    "bare=False 表示该字噪声过大、只保留多字写法。"
                    "charGuards 是单字地名的上下文守卫（aft/bfr 邻字排除）。",
        "places": places,
        "charGuards": guards,
        "bareOff": sorted(BARE_OFF),
        "nameBlock": sorted(NAME_BLOCK),
        # 守卫只放行「地名+谥号+爵位」三段式（周文王 / 宋襄公 / 陳武公）：
        # 阻断串须是 2 字、末字是谥号字，且其后紧跟爵位字。两个集合都必须精确——
        # 把 軍/兵/將/相/守 也算爵位字，会把「秦嘉軍敗走」这类全放行；
        # 谥号字表漏一个「襄」，「宋襄公」的「宋」就会被误挡。故用 POSTHUMOUS_ALL。
        "nameBlockPeerage": "".join(sorted(PEERAGE_CHARS)),
        "nameBlockPosthumous": "".join(sorted(POSTHUMOUS_ALL)),
    }
    with open(os.path.join(DICT, "places.json"), "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)

    by_kind = {}
    for p in places:
        by_kind.setdefault(p["kind"], []).append(p["name"])
    chars = [p["name"] for p in places if p["isChar"]]
    report = {
        "placeCount": len(places),
        "aliasCount": total_aliases,
        "charPlaces": chars,
        "bareOff": sorted(BARE_OFF),
        "byKind": {k: len(v) for k, v in sorted(by_kind.items())},
        "kinds": {k: v for k, v in sorted(by_kind.items())},
        "guardCount": len(guards),
        "nameBlockCount": len(NAME_BLOCK),
    }
    with open(os.path.join(ROOT, "pipeline", "_place_report.json"), "w",
              encoding="utf-8") as fh:
        json.dump(report, fh, ensure_ascii=False, indent=2)

    print("地名 {} / 写法 {} / 类型 {}".format(
        len(places), total_aliases, report["byKind"]))
    print("单字国名 {} 个：{}".format(len(chars), "".join(chars)))
    print("不做裸匹配：{}".format("".join(sorted(BARE_OFF))))


if __name__ == "__main__":
    main()
